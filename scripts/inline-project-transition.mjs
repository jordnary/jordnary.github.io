import { readFile, writeFile } from 'node:fs/promises'
import { Script } from 'node:vm'
import { bootstrapProjectTransition } from '../src/lib/projectTransitionBoot.ts'
import { projectTransitionMotion } from '../src/lib/projectTransitionMotion.ts'

const templates = ['projects/index.html', 'projects/studio/index.html']
const stylesheet = 'src/components/ProjectPageTransition.css'
const startMarker = '<!-- project-transition-bootstrap:start -->'
const endMarker = '<!-- project-transition-bootstrap:end -->'
const root = new URL('../', import.meta.url)

function replaceBootstrap(source, css, script, name) {
  const starts = source.split(startMarker).length - 1
  const ends = source.split(endMarker).length - 1
  if (starts !== ends || starts > 1) throw new Error(`${name}: bootstrap markers must be a unique pair`)

  if (starts) {
    const start = source.indexOf(startMarker)
    const end = source.indexOf(endMarker)
    if (end < start) throw new Error(`${name}: bootstrap markers are reversed`)
    const lineStart = source.lastIndexOf('\n', start) + 1
    const after = end + endMarker.length
    const trailing = source.slice(after).match(/^[\t ]*(?:\r?\n|$)/)
    if (source.slice(lineStart, start).trim() || !trailing) {
      throw new Error(`${name}: bootstrap markers must occupy their own lines`)
    }
    source = source.slice(0, lineStart) + source.slice(after + trailing[0].length)
  }

  const viewport = /^([\t ]*)<meta\b(?=[^\r\n>]*\bname\s*=\s*["']viewport["'])[^\r\n>]*>[\t ]*(?=\r?$)/im.exec(source)
  if (!viewport) throw new Error(`${name}: viewport metadata is missing`)
  const eol = source.includes('\r\n') ? '\r\n' : '\n'
  const indent = viewport[1]
  const content = value => value.trim().split(/\r?\n/).map(line => line.trimEnd())
    .map(line => line ? `${indent}  ${line}` : '').join(eol)
  const fragment = [
    `${indent}${startMarker}`,
    `${indent}<!-- Generated by scripts/inline-project-transition.mjs; edit the shared sources. -->`,
    `${indent}<style data-project-transition-bootstrap>`,
    content(css),
    `${indent}</style>`,
    `${indent}<script data-project-transition-bootstrap>`,
    content(script),
    `${indent}</script>`,
    `${indent}${endMarker}`,
  ].join(eol)
  const insertion = viewport.index + viewport[0].length
  return source.slice(0, insertion) + eol + fragment + source.slice(insertion)
}

async function main() {
  const args = process.argv.slice(2)
  if (args.some(arg => arg !== '--check') || args.length > 1) {
    throw new Error('Usage: node scripts/inline-project-transition.mjs [--check]')
  }
  const check = args.includes('--check')
  const [css, ...sources] = await Promise.all([
    readFile(new URL(stylesheet, root), 'utf8'),
    ...templates.map(name => readFile(new URL(name, root), 'utf8')),
  ])
  if (/<\/style/i.test(css)) throw new Error(`${stylesheet}: inline styles cannot contain a closing style tag`)

  // Node strips the TypeScript annotations before exposing the function source.
  // The bootstrap has no runtime imports or module-scoped dependencies.
  const script = `(${bootstrapProjectTransition.toString()})(${JSON.stringify(projectTransitionMotion)});`
    .replace(/<\/script/gi, '<\\/script')
  new Script(script, { filename: 'project-transition-bootstrap.inline.js' })

  // Validate both templates before changing either one.
  const changes = templates.map((name, index) => ({
    name,
    original: sources[index],
    next: replaceBootstrap(sources[index], css, script, name),
  })).filter(({ original, next }) => original !== next)
  if (check) {
    if (changes.length) throw new Error(`Outdated Projects bootstrap: ${changes.map(({ name }) => name).join(', ')}. Run npm run sync:project-transition.`)
    console.log('Projects bootstrap is synchronized.')
    return
  }
  for (const { name, next } of changes) {
    await writeFile(new URL(name, root), next)
    console.log(`Updated ${name}`)
  }
  if (!changes.length) console.log('Projects bootstrap is already synchronized.')
}

main().catch(error => {
  console.error(error.message)
  process.exitCode = 1
})
